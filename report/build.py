"""Build the project report from the Claude Doc's markdown export and check the page limit.

The report is written in a Claude Doc ("Forager: CS 619 project report"); report.md is its markdown export.
The doc's own PDF export uses large type, so this script typesets the same text with report.css (A4, Times
9.5pt): it converts report.md to report.html with pandoc, puts the figures back (the export replaces each
picture with a placeholder) and prints report.html to forager-report.pdf with headless Google Chrome.

The main body (everything before the appendix) must fit in six A4 pages; the appendix holds figures and
supplementary tables. The report is printed twice: once in full, and once with ?main, which drops the
appendix, to count the main body's pages.

Run: .venv/bin/python report/build.py
"""

import html
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MARKDOWN = ROOT / "report.md"
SOURCE = ROOT / "report.html"
OUT = ROOT / "forager-report.pdf"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
PANDOC = shutil.which("pandoc") or "/Applications/anaconda3/bin/pandoc"
MAX_MAIN_PAGES = 6

# Each picture goes back in by its caption's label: (file, width as a percentage of the text column).
FIGURES = {
    "Figure 1": ("figures/architecture.svg", 100),
    "Figure A1": ("figures/setup-options.png", 85),
    "Figure A2": ("figures/brief-top.png", 55),
    "Figure A3": ("figures/proposal.png", 58),
    "Figure A4": ("figures/critic.png", 60),
    "Figure A5": ("figures/topics.png", 92),
    "Figure A6": ("figures/timeline-sketch.svg", 100),
}

HEAD = """<!doctype html>
<!-- Generated by build.py from report.md, the Claude Doc's markdown export. Edit the doc, not this file. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>Forager: CS 619 Project Report</title>
<meta name="description" content="CS 619 project report for Forager, a personalized agent that delivers a daily, source-traceable AI brief.">
<link rel="stylesheet" href="report.css">
<script>
  // build.py prints the report twice: in full, and with ?main to count the main body's pages.
  if (location.search.includes("main")) {
    document.addEventListener("DOMContentLoaded", () => document.querySelectorAll(".appendix").forEach(e => e.remove()));
  }
</script>
</head>
<body>
"""


def to_html(markdown: str) -> str:
    """The export as an HTML fragment, with FIGURE-SLOT where each picture was."""
    markdown = re.sub(r"^&#91;image: .*\\\]$", "FIGURE-SLOT", markdown, flags=re.M)
    # A large --columns keeps pandoc from fixing column widths, so the browser sizes them to their content.
    return subprocess.run([PANDOC, "-f", "gfm", "-t", "html5", "--wrap=none", "--columns=100000"],
                          input=markdown, capture_output=True, text=True, check=True).stdout


def title_block(match: re.Match) -> str:
    title, byline, links = match.groups()
    parts = [p.strip() for p in html.unescape(byline).split("·")]
    course = next((p for p in parts if "Report" in p), None)
    author = " · ".join(parts[:parts.index(course)]) if course else byline
    return ('<header class="title-block">\n'
            f'  <p class="course">{course or "CS 619 Project Report"}</p>\n'
            f'  <p class="title">{title}</p>\n'
            f'  <p class="author">{author}</p>\n'
            f'  <p class="links">{links}</p>\n'
            '</header>\n')


def figure(match: re.Match) -> str:
    label, caption = match.groups()
    source, width = FIGURES[label]
    if source.endswith(".svg"):
        art = (ROOT / source).read_text(encoding="utf-8")
    else:
        art = f'<img class="shot" src="{source}" alt="">'
    return (f'<figure style="width: {width}%; margin-left: auto; margin-right: auto">{art}'
            f'<figcaption><strong>{label}.</strong>{caption}</figcaption></figure>')


def page(fragment: str) -> str:
    body = re.sub(r"<h1[^>]*>(.*?)</h1>\s*<p>(.*?)</p>\s*<p>(Code and evaluation data:.*?)</p>", title_block,
                  fragment, count=1, flags=re.S)
    body = re.sub(r"(<h[23][^>]*>)(\d+(?:\.\d+)?) ", r"\1\2&ensp;", body)
    body = re.sub(r"<p>FIGURE-SLOT</p>\s*<p><strong>(Figure A?\d+)\.</strong>(.*?)</p>", figure, body, flags=re.S)
    body = re.sub(r"<p><strong>(Table A?\d+\.)</strong>(.*?)</p>\s*(<table[^>]*>.*?</table>)",
                  r'<div class="table-wrap"><p class="table-caption"><strong>\1</strong>\2</p>\3</div>',
                  body, flags=re.S)
    # Numbers and intervals stay on one line; the tables still fit the column, so Chrome does not shrink the page.
    body = re.sub(r"<td([^>]*)>((?:<strong>)?[−+$\d][−+$\d.,%\[\] /s]*(?:</strong>)?)</td>",
                  r'<td\1 class="nowrap">\2</td>', body)
    body = re.sub(r"(<h2[^>]*>References</h2>)\s*(<ol>.*?</ol>)", r'\1\n<div class="refs">\2</div>', body, flags=re.S)
    # What the user study will fill: bracketed bold notes and cells that are only question marks.
    body = re.sub(r"<strong>(\[.*?\])</strong>", r'<strong class="todo">\1</strong>', body)
    body = re.sub(r"<td([^>]*)>([?/ ]*\?[?/ ]*)</td>", r'<td\1 class="todo">\2</td>', body)
    if "FIGURE-SLOT" in body:
        raise SystemExit("a picture in report.md has no caption that FIGURES knows")
    start = re.search(r"<h2[^>]*>Appendix", body)
    if start:
        appendix = re.sub(r"(</h2>\s*)<p>", r'\1<p class="lede">', body[start.start():], count=1)
        body = body[:start.start()] + '<section class="appendix">\n' + appendix + "</section>\n"
    return HEAD + body + "</body>\n</html>\n"


def print_pdf(url: str, out: Path) -> int:
    with tempfile.TemporaryDirectory(prefix="forager-report-") as profile:
        subprocess.run([CHROME, "--headless=new", "--disable-gpu", f"--user-data-dir={profile}", "--no-first-run",
                        "--no-pdf-header-footer", "--run-all-compositor-stages-before-draw",
                        "--virtual-time-budget=8000", f"--print-to-pdf={out}", url],
                       check=True, capture_output=True, timeout=120)
    return len(re.findall(rb"/Type\s*/Page(?!s)", out.read_bytes()))


def main() -> int:
    SOURCE.write_text(page(to_html(MARKDOWN.read_text(encoding="utf-8"))), encoding="utf-8")
    url = SOURCE.as_uri()
    pages = print_pdf(url, OUT)
    with tempfile.TemporaryDirectory() as tmp:
        main_pages = print_pdf(url + "?main", Path(tmp) / "main.pdf")
    print(f"{OUT.relative_to(ROOT.parent)}: {pages} pages (main body {main_pages}, appendix {pages - main_pages})")
    if main_pages > MAX_MAIN_PAGES:
        print(f"the main body is over {MAX_MAIN_PAGES} pages")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
