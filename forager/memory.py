"""Idea 2: consented, evidence-backed preference memory.

The memory agent reads the profile and the signals the user allowed, and may
call propose_profile_update. That tool is declared with needs_approval=True, so
the SDK pauses the run and nothing is written unless the user approves. Before
the user is asked, code checks the proposal: at least two distinct consented
signals as evidence, a valid target, not a repeat of a recent rejection, and at
most three proposals per review. Invalid proposals are blocked with the reason
sent back to the model. The tool body checks again before writing.

The user sees a change description and the evidence generated by code from the
arguments and the signal log, next to the agent's message, so a misleading
message cannot hide what will actually change.

Baseline (silent updates): the same agent and tool with needs_approval=False.
"""

import json
from copy import deepcopy
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path

from .jsonagent import context_input
from .onboarding import SHORT_TERM_DAYS, save_profile
from .profile import RUNTIME_DIR, is_expired, load_profile
from .signals import SIGNALS, describe, load_signals, usable_signals

MIN_EVIDENCE = 2
MAX_PROPOSALS = 3
REJECTION_MEMORY_DAYS = 30
MAX_CONTEXT_SIGNALS = 80
ACTIONS = ("add_interest", "change_weight", "remove_interest", "set_type")
TYPES = ("long_term", "short_term")
ARGUMENTS = ("action", "message", "evidence", "interest_id", "label", "interest_type", "weight")

MEMORY_INSTRUCTIONS = """You maintain a Forager user's interest profile from their feedback.
You receive the current profile, the feedback signals the user allowed Forager to
use (each with an ID), the signal types that are not tracked, and changes the user
recently rejected.

Propose a change only when at least two signals clearly support it. Call
propose_profile_update once per change, at most 3 changes. For example:
- Several high ratings or likes on one release or event: add it as a short_term
  interest (it expires after 14 days).
- Repeated interest in a topic that is not in the profile: add a long_term interest.
- Consistently low ratings for an interest: lower its weight. Remove it only when
  the evidence is strong.
- A short_term interest that keeps getting high ratings: set_type long_term.

In message, state the evidence in plain words and ask a yes/no question, e.g.
"You rated three Sora items 5/5. Add video generation as a short-term focus?"
Cite only signal IDs you were given; never guess at signals that are not tracked.
Do not propose a change the user rejected. If a proposal is rejected or blocked,
do not retry it. Never say a change was made unless the tool result says so.
If the evidence does not clearly support any change, propose nothing.
Finish with one or two sentences: what you proposed and what happened.
"""

REQUEST = "Review my recent feedback and propose profile updates only where the evidence supports them."


def _now():
    return datetime.now().isoformat(timespec="seconds")


def _plus_days(today: str, days: int) -> str:
    return (date.fromisoformat(today) + timedelta(days=days)).isoformat()


def normalize(arguments: dict) -> dict:
    proposal = {name: arguments.get(name) for name in ARGUMENTS}
    evidence = proposal["evidence"] if isinstance(proposal["evidence"], list) else []
    proposal["evidence"] = list(dict.fromkeys(str(e) for e in evidence))
    return proposal


def _interest(profile, interest_id):
    return next((i for i in profile.get("interests", []) if i["id"] == interest_id), None)


def change_key(proposal: dict, profile: dict) -> list:
    """What a proposal changes, independent of wording; used to remember rejections."""
    action = proposal.get("action")
    if action == "add_interest":
        return [action, str(proposal.get("label") or "").strip().casefold()]
    interest = _interest(profile, proposal.get("interest_id")) or {}
    target = str(interest.get("label", proposal.get("interest_id"))).casefold()
    if action == "set_type":
        return [action, target, proposal.get("interest_type")]
    if action == "change_weight":
        weight = proposal.get("weight") or 0
        return [action, target, "up" if weight > interest.get("weight", 0) else "down"]
    return [action, target]


def describe_change(proposal: dict, profile: dict, today: str) -> str:
    """The change in plain words, generated by code from the tool arguments."""
    action = proposal.get("action")
    term = (lambda t: f"a short-term interest until {_plus_days(today, SHORT_TERM_DAYS)}"
            if t == "short_term" else "a long-term interest")
    if action == "add_interest":
        return f'Add "{proposal.get("label")}" as {term(proposal.get("interest_type"))} (weight {proposal.get("weight")})'
    interest = _interest(profile, proposal.get("interest_id")) or {"label": proposal.get("interest_id")}
    if action == "change_weight":
        return f'Change the weight of "{interest["label"]}" from {interest.get("weight")} to {proposal.get("weight")}'
    if action == "remove_interest":
        return f'Remove "{interest["label"]}" from your profile'
    if action == "set_type":
        return f'Make "{interest["label"]}" {term(proposal.get("interest_type"))}'
    return f"Unknown change ({action})"


def check_proposal(proposal: dict, profile: dict, usable_ids, rejections=(), today=None) -> list[str]:
    """Code checks every proposal must pass before the user sees it and again before writing."""
    errors = []
    action = proposal.get("action")
    if action not in ACTIONS:
        return [f"action must be one of: {', '.join(ACTIONS)}."]
    message = str(proposal.get("message") or "").strip()
    if not message:
        errors.append("message must state the evidence to the user and ask a yes/no question.")
    elif len(message) > 400:
        errors.append("message must be under 400 characters.")
    evidence = proposal.get("evidence") or []
    unknown = [e for e in evidence if e not in usable_ids]
    if unknown:
        errors.append(f"Evidence {', '.join(unknown)} is not among the consented signals you were given.")
    if len(evidence) - len(unknown) < MIN_EVIDENCE:
        errors.append(f"Cite at least {MIN_EVIDENCE} distinct consented signal IDs as evidence.")

    weight = proposal.get("weight")
    weight_ok = isinstance(weight, (int, float)) and not isinstance(weight, bool) and 0 < weight <= 1
    if action == "add_interest":
        label = str(proposal.get("label") or "").strip()
        if not label:
            errors.append("add_interest needs a label.")
        elif label.casefold() in {i["label"].casefold() for i in profile.get("interests", [])}:
            errors.append(f'"{label}" is already in the profile; use change_weight or set_type instead.')
        if proposal.get("interest_type") not in TYPES:
            errors.append("add_interest needs interest_type long_term or short_term.")
        if not weight_ok:
            errors.append("add_interest needs a weight between 0 (exclusive) and 1.")
    else:
        interest = _interest(profile, proposal.get("interest_id"))
        if interest is None:
            ids = ", ".join(i["id"] for i in profile.get("interests", []))
            errors.append(f"interest_id must be one of: {ids}.")
        elif action == "change_weight":
            if not weight_ok:
                errors.append("change_weight needs a weight between 0 (exclusive) and 1.")
            elif weight == interest.get("weight"):
                errors.append("The new weight equals the current weight.")
        elif action == "set_type":
            if proposal.get("interest_type") not in TYPES:
                errors.append("set_type needs interest_type long_term or short_term.")
            elif proposal["interest_type"] == interest.get("type") and not is_expired(interest, today):
                errors.append(f'"{interest["label"]}" is already {interest["type"]}.')

    key = change_key(proposal, profile)
    for rejected in rejections:
        if rejected.get("key") == key:
            errors.append(f"The user rejected this change on {rejected['time'][:10]}; do not propose it again.")
            break
    return errors


def apply_change(profile: dict, proposal: dict, events: dict, today: str, *, approved: bool) -> dict:
    """Return a new profile with the change applied. Evidence is copied from the signal log."""
    profile = deepcopy(profile)
    evidence = [describe(events[e]) for e in proposal["evidence"] if e in events]
    stamp = {"approved_on": today} if approved else {"updated_silently_on": today}
    action = proposal["action"]
    if action == "add_interest":
        number = max([int(i["id"][1:]) for i in profile["interests"] if i["id"][1:].isdigit()] or [0]) + 1
        short = proposal["interest_type"] == "short_term"
        profile["interests"].append({
            "id": f"i{number}", "label": proposal["label"].strip(), "facets": [],
            "type": proposal["interest_type"], "source": "inferred", "weight": proposal["weight"],
            "expires": _plus_days(today, SHORT_TERM_DAYS) if short else None,
            "origin": "proposal", "evidence": evidence, **stamp})
        return profile
    interest = _interest(profile, proposal["interest_id"])
    if action == "remove_interest":
        profile["interests"].remove(interest)
        return profile
    if action == "change_weight":
        interest["weight"] = proposal["weight"]
    elif action == "set_type":
        interest["type"] = proposal["interest_type"]
        interest["expires"] = (_plus_days(today, SHORT_TERM_DAYS)
                               if proposal["interest_type"] == "short_term" else None)
    interest["evidence"] = (interest.get("evidence") or []) + evidence
    interest.update(stamp)
    return profile


@dataclass
class MemoryStore:
    """Where the profile, signals and proposal log live, plus this review's records."""
    runtime: Path = RUNTIME_DIR
    today: str = field(default_factory=lambda: date.today().isoformat())
    log: list = field(default_factory=list)
    shown: int = 0

    @property
    def profile_path(self):
        return self.runtime / "profile.json"

    @property
    def signals_path(self):
        return self.runtime / "signals.jsonl"

    @property
    def proposals_path(self):
        return self.runtime / "proposals.jsonl"

    def profile(self) -> dict:
        return load_profile(self.profile_path)

    def usable(self) -> list[dict]:
        return usable_signals(self.profile(), load_signals(self.signals_path), self.today)

    def history(self) -> list[dict]:
        if not self.proposals_path.exists():
            return []
        return [json.loads(line) for line in self.proposals_path.read_text().splitlines() if line.strip()]

    def recent_rejections(self) -> list[dict]:
        since = _plus_days(self.today, -REJECTION_MEMORY_DAYS)
        return [r for r in self.history() if r["decision"] == "rejected" and r["time"][:10] >= since]

    def record(self, proposal: dict, profile: dict, decision: str, *, mode: str, events=None,
               errors=(), applied=False, change=None) -> dict:
        events = events or {}
        entry = {"time": _now(), "mode": mode, "decision": decision, "applied": applied,
                 "change": change or describe_change(proposal, profile, self.today),
                 "key": change_key(proposal, profile), "message": proposal.get("message"),
                 "evidence_ids": proposal.get("evidence", []),
                 "evidence": [describe(events[e]) for e in proposal.get("evidence", []) if e in events],
                 "errors": list(errors), "proposal": proposal}
        self.proposals_path.parent.mkdir(parents=True, exist_ok=True)
        with self.proposals_path.open("a") as out:
            out.write(json.dumps(entry, ensure_ascii=False) + "\n")
        self.log.append(entry)
        return entry

    def errors_for(self, proposal, profile, events, *, check_limit) -> list[str]:
        errors = check_proposal(proposal, profile, events, self.recent_rejections(), self.today)
        if check_limit and self.shown >= MAX_PROPOSALS:
            errors.append(f"At most {MAX_PROPOSALS} proposals per review; stop proposing.")
        return errors


def apply_proposal(store: MemoryStore, events: dict, arguments: dict, *, silent: bool) -> dict:
    """Tool body. Approval mode: runs only after the user approved. Silent: runs directly."""
    proposal = normalize(arguments)
    profile = store.profile()
    mode = "silent" if silent else "approval"
    errors = store.errors_for(proposal, profile, events, check_limit=silent)
    if errors:
        store.record(proposal, profile, "blocked" if silent else "approved_not_applied",
                     mode=mode, events=events, errors=errors)
        return {"ok": False, "error": "Not applied: " + " ".join(errors)}
    if silent:
        store.shown += 1
    change = describe_change(proposal, profile, store.today)
    save_profile(apply_change(profile, proposal, events, store.today, approved=not silent), store.profile_path)
    store.record(proposal, profile, "silent" if silent else "approved", mode=mode, events=events,
                 applied=True, change=change)
    return {"ok": True, "applied": change}


def memory_agent_factory(store: MemoryStore, events: dict, *, silent=False):
    def create(model):
        from agents import Agent, function_tool

        @function_tool(needs_approval=not silent)
        def propose_profile_update(action: str, message: str, evidence: list[str], interest_id: str | None,
                                   label: str | None, interest_type: str | None,
                                   weight: float | None) -> str:
            """Propose one change to the user's interest profile. The user sees the change and
            its evidence and must approve it; nothing is written otherwise.

            Args:
                action: add_interest, change_weight, remove_interest or set_type.
                message: One or two sentences to the user that state the evidence in plain words
                    and ask a yes/no question.
                evidence: IDs of at least two consented signals that support the change.
                interest_id: The profile interest to change; null for add_interest.
                label: Name of the new interest for add_interest; otherwise null.
                interest_type: long_term or short_term for add_interest and set_type; otherwise null.
                weight: 0-1 for add_interest and change_weight; otherwise null.
            """
            # JSON (not a dict's repr) so the model and the lab's tool events read it correctly.
            return json.dumps(apply_proposal(store, events, {
                "action": action, "message": message, "evidence": evidence, "interest_id": interest_id,
                "label": label, "interest_type": interest_type, "weight": weight}, silent=silent))

        return Agent(name="Memory agent", model=model, instructions=MEMORY_INSTRUCTIONS,
                     tools=[propose_profile_update])
    return create


def approval_runner(store: MemoryStore, events: dict, decide, max_turns=8):
    """Runner that settles each approval interruption: block in code, else ask the user."""
    def run(agent, messages, run_config=None):
        from agents import Runner
        result = Runner.run_sync(agent, messages, max_turns=max_turns, run_config=run_config)
        while result.interruptions:
            state = result.to_state()
            for interruption in result.interruptions:
                try:
                    proposal = normalize(json.loads(interruption.arguments or "{}"))
                except ValueError:
                    proposal = normalize({})
                profile = store.profile()
                errors = store.errors_for(proposal, profile, events, check_limit=True)
                if errors:
                    store.record(proposal, profile, "blocked", mode="approval", events=events, errors=errors)
                    state.reject(interruption, rejection_message=(
                        "Blocked by Forager's checks; the user was not asked. " + " ".join(errors)))
                    continue
                store.shown += 1
                view = {"message": proposal["message"], "change": describe_change(proposal, profile, store.today),
                        "evidence": [describe(events[e]) for e in proposal["evidence"]]}
                if decide(view):
                    state.approve(interruption)  # The tool body now writes the change.
                else:
                    store.record(proposal, profile, "rejected", mode="approval", events=events)
                    state.reject(interruption, rejection_message=(
                        "The user rejected this proposal. The profile is unchanged. Do not propose it again."))
            result = Runner.run_sync(agent, state, max_turns=max_turns, run_config=run_config)
        return result
    return run


def silent_runner(agent, messages, run_config=None):
    from agents import Runner
    return Runner.run_sync(agent, messages, max_turns=8, run_config=run_config)


def memory_context(store: MemoryStore, profile: dict, usable: list[dict]) -> str:
    consent = profile.get("consent", {})
    return json.dumps({
        "today": store.today,
        "profile": [{**{k: i.get(k) for k in ("id", "label", "facets", "type", "source", "weight", "expires")},
                     "status": "expired" if is_expired(i, store.today) else "active"}
                    for i in profile.get("interests", [])],
        "signals": [{"id": e["id"], "signal": e["signal"], "value": e["value"], "date": e["time"][:10],
                     "item": e["item"]} for e in usable[-MAX_CONTEXT_SIGNALS:]],
        "not_tracked": [s for s in SIGNALS if not consent.get(s, False)],
        "recent_rejections": [{"date": r["time"][:10], "change": r["change"]} for r in store.recent_rejections()],
    }, ensure_ascii=False)


def review(lab, store: MemoryStore, decide=None, *, silent=False, on_event=None) -> dict:
    """Run one memory review. decide(view) -> bool asks the user (approval mode only)."""
    if not silent and decide is None:
        raise ValueError("Approval mode needs a decide(view) callback that asks the user.")
    profile = store.profile()
    usable = store.usable()
    if len(usable) < MIN_EVIDENCE:
        return {"status": "skipped", "answer": "", "proposals": [],
                "reason": f"Fewer than {MIN_EVIDENCE} consented signals from the last 30 days; nothing to learn from."}
    events = {e["id"]: e for e in usable[-MAX_CONTEXT_SIGNALS:]}
    runner = silent_runner if silent else approval_runner(store, events, decide)
    session = lab.session(agent_factory=memory_agent_factory(store, events, silent=silent), runner=runner,
                          input_builder=context_input("Memory context", memory_context(store, profile, usable)),
                          on_event=on_event, agent_id="memory-agent")
    result = session.run(REQUEST)
    return {"status": result.status, "answer": result.answer, "error": result.error,
            "proposals": list(store.log), "turn": result.to_dict()}


def resolve_expired(store: MemoryStore, interest_id: str, choice: str) -> str:
    """The user's decision on an expired short-term interest (no model involved)."""
    profile = store.profile()
    interest = _interest(profile, interest_id)
    if interest is None or not is_expired(interest, store.today):
        raise ValueError(f"{interest_id} is not an expired short-term interest.")
    updated = deepcopy(profile)
    target = _interest(updated, interest_id)
    if choice == "keep":
        target["expires"] = _plus_days(store.today, SHORT_TERM_DAYS)
        change, decision = f'Keep "{interest["label"]}" short-term until {target["expires"]}', "kept"
    elif choice == "long":
        target["type"], target["expires"] = "long_term", None
        change, decision = f'Make "{interest["label"]}" a long-term interest', "made_long_term"
    elif choice == "remove":
        updated["interests"].remove(target)
        change, decision = f'Remove expired "{interest["label"]}"', "removed"
    else:
        raise ValueError("Choose keep, long or remove.")
    save_profile(updated, store.profile_path)
    store.record({"action": f"expiry_{choice}", "interest_id": interest_id, "evidence": []}, profile,
                 decision, mode="expiry", applied=True, change=change)
    return change
